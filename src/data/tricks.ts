export const TRICKS_BY_ID: Record<string, TrickDef> = Object.fromEntries(
  TRICKS.map((t) => [t.id, t]),
);

export function tricksForApparatus(apparatusId: ApparatusId): TrickDef[] {
  return TRICKS.filter((t) => t.apparatusIds.includes(apparatusId)).sort(
    (a, b) => a.level - b.level,
  );
}
